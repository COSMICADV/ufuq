const APRIL_RANGE = 'from=2026-04-01&to=2026-04-30';

interface Report {
  readonly report: {
    readonly key: string;
    readonly scope: { readonly type: string; readonly manager_employee_id?: string };
    readonly range: { readonly from: string; readonly to: string } | null;
    readonly filters: Record<string, string>;
    readonly filter_labels: Record<string, { ar: string; en: string }>;
    readonly timezone: string;
    readonly generated_at: string;
    readonly provisional: boolean;
    readonly provisional_reason: string | null;
    readonly trend_unit: string | null;
  };
  readonly summary: Record<string, unknown>;
  readonly groups: Record<string, Record<string, unknown>[]>;
  readonly trend: { period: string; values: Record<string, unknown> }[];
  readonly rows: Record<string, unknown>[];
  readonly pagination: { page: number; per_page: number; total: number; total_pages: number };
}

async function report(account: Account, path: string): Promise<Report> {
  const response = await (await api(account)).get(path);
  if (response.status !== 200) {
    throw new Error(`${path}: ${String(response.status)} ${JSON.stringify(response.body)}`);
  }
  return response.body.data as Report;
}

function rowOf(rows: readonly Record<string, unknown>[], field: string, value: unknown) {
  const found = rows.find((row) => row[field] === value);
  if (found === undefined) throw new Error(`No row with ${field} = ${String(value)}`);
  return found;
}

function money(values: readonly string[]): string {
  return Decimal.sum(
    values.map((v) => Decimal.parse(v, 2)),
    2,
  ).toString();
}

