type Status = 'present' | 'late' | 'absent' | 'half_day';
interface Day {
  readonly status: Status;
  readonly wfh?: boolean;
}

function daysOf(year: number, month: number): string[] {
  const last = new Date(Date.UTC(year, month, 0)).getUTCDate();
  return Array.from(
    { length: last },
    (_, i) => `${String(year)}-${String(month).padStart(2, '0')}-${String(i + 1).padStart(2, '0')}`,
  );
}

function isWeekend(date: string): boolean {
  return new Date(`${date}T00:00:00.000Z`).getUTCDay() >= 5;
}

/** April exceptions; every other working day is present at the office. */
const APRIL: Record<string, Record<string, Day>> = {
  worker: {
    '2026-04-05': { status: 'late' },
    '2026-04-06': { status: 'absent' },
    '2026-04-07': { status: 'present', wfh: true },
    '2026-04-08': { status: 'present', wfh: true },
  },
  worker2: { '2026-04-20': { status: 'half_day' } },
  outsider: { '2026-04-21': { status: 'absent' }, '2026-04-22': { status: 'late' } },
  manager: {},
};
/** Sara's approved (unpaid) leave, written as `on_leave` by the leave module. */
const SARA_LEAVE = ['2026-04-14', '2026-04-15'];

async function seedMonth(
  employeeId: string,
  year: number,
  month: number,
  overrides: Record<string, Day>,
) {
  const rows = daysOf(year, month).map((date) => {
    const weekend = isWeekend(date);
    const day = overrides[date] ?? { status: 'present' as Status };
    const worked = !weekend && day.status !== 'absent';
    return {
      id: generateId(),
      companyId: COMPANY_A,
      employeeId,
      date: new Date(`${date}T00:00:00.000Z`),
      status: weekend ? ('weekend' as const) : day.status,
      source: weekend ? ('system' as const) : ('self' as const),
      workMode: worked ? (day.wfh === true ? ('wfh' as const) : ('office' as const)) : null,
      checkInAt: worked ? new Date(`${date}T07:00:00.000Z`) : null,
      checkOutAt: worked ? new Date(`${date}T15:00:00.000Z`) : null,
      workingMinutes: worked ? 420 : null,
      lateMinutes: day.status === 'late' ? 20 : worked ? 0 : null,
      overtimeMinutes: worked ? 0 : null,
    };
  });
  await withTenant(prisma, COMPANY_A, (tx) =>
    tx.attendanceRecord.createMany({ data: rows, skipDuplicates: true }),
  );
}

/** What the attendance report must say for one employee's April, from the seed alone. */
function expectedApril(key: keyof typeof APRIL) {
  const working = daysOf(2026, 4).filter((d) => !isWeekend(d));
  const leave = key === 'worker2' ? SARA_LEAVE : [];
  const counts = {
    working_days: working.length,
    present: 0,
    office: 0,
    wfh: 0,
    late: 0,
    half_day: 0,
    absent: 0,
    leave: 0,
  };
  for (const date of working) {
    if (leave.includes(date)) {
      counts.leave += 1;
      continue;
    }
    const day = APRIL[key]?.[date] ?? { status: 'present' };
    if (day.status === 'absent') {
      counts.absent += 1;
      continue;
    }
    counts.present += 1;
    if (day.wfh === true) counts.wfh += 1;
    else counts.office += 1;
    if (day.status === 'late') counts.late += 1;
    if (day.status === 'half_day') counts.half_day += 1;
  }
  return counts;
}

